    @staticmethod
    def horario_listar_nao_confirmados_hoje():
        hoje = datetime.now().date()
        resultado = []
        for horario in Service.horario_listar():
            data = horario.get_data()
            if isinstance(data, str):
                try: data = datetime.fromisoformat(data)
                except ValueError:
                    try: data = datetime.strptime(data, "%d/%m/%Y %H:%M")
                    except ValueError:
                        continue
            if data.date() != hoje:
                continue
            if horario.get_confirmado():
                continue
            id_cliente = horario.get_id_cliente()
            if not id_cliente:
                continue
            cliente = Service.cliente_listar_id(id_cliente)
            servico = Service.servico_listar_id(horario.get_id_servico())
            profissional = Service.profissional_listar_id(horario.get_id_profissional())
            if cliente and servico and profissional:
                resultado.append({"data": data,"cliente": cliente.get_nome(),"servico": servico.get_descricao(),"profissional": profissional.get_nome()})
        return sorted(resultado, key=lambda item: item["data"])
    
    @staticmethod
    def horario_listar_agenda_cliente(id_cliente):
        resultado = []
        for horario in Service.horario_listar():
            if horario.get_id_cliente() != id_cliente:
                continue
            data = horario.get_data()
            if isinstance(data, str):
                try: data = datetime.fromisoformat(data)
                except ValueError:
                    try: data = datetime.strptime(data, "%d/%m/%Y %H:%M")
                    except ValueError:
                        continue
            servico = Service.servico_listar_id(horario.get_id_servico())
            profissional = Service.profissional_listar_id(horario.get_id_profissional())
            if servico and profissional:
                resultado.append({"data": data,"profissional": profissional.get_nome(),"servico": servico.get_descricao()})
        return sorted(resultado, key=lambda item: item["data"])

